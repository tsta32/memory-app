'use strict';
const assert=require('node:assert/strict');
const {createHash}=require('node:crypto');
const {keys,inspect}=require('../sync-integrity');
const {validateDeviceReceipt,verifyPublished,verifySyncedOnly}=require('../scripts/refresh-sentence-task.cjs');
const fixture=Object.fromEntries(keys.map(key=>[key,'{}']));
fixture.srs_cards_v2='{"cards":[{"id":1,"en":"Synthetic example","ko":"Fixture translation","priority":"important","context":"Fixture context","chapterId":1}],"editHistory":[{"field":"en","before":"Fixture original","value":"Synthetic example"}]}';
fixture.srs_chapters_v1='{"chapters":[{"id":1,"name":"Fixture category"}]}';
const hash=text=>createHash('sha256').update(text).digest('hex');
const now=Date.now(),checkedAt=new Date(now).toISOString();
const data=inspect(fixture);
assert.equal(inspect({...fixture,srs_cards_v2:JSON.stringify(JSON.parse(fixture.srs_cards_v2),null,2)}).canonical,data.canonical);
assert.notEqual(inspect({...fixture,srs_cards_v2:fixture.srs_cards_v2.replace('Fixture original','Different original')}).canonical,data.canonical);
assert.notEqual(inspect({...fixture,srs_chapters_v1:fixture.srs_chapters_v1.replace('Fixture category','Different category')}).canonical,data.canonical);
assert.throws(()=>inspect({...fixture,srs_settings_v1:undefined}),/required storage/);
assert.equal(inspect({...fixture,srs_settings_v1:'{"grammarOptions":{"article":true,"tense":true}}'}).canonical,
  inspect({...fixture,srs_settings_v1:'{"grammarOptions":{"article":true}}'}).canonical);
assert.notEqual(inspect({...fixture,srs_settings_v1:'{"grammarOptions":{"article":false}}'}).canonical,
  inspect({...fixture,srs_settings_v1:'{"grammarOptions":{"article":true}}'}).canonical);
const device={version:1,snapshotVersion:1,hashVersion:1,storageKeyCount:7,pending:false,checkedAt,lastSuccessAt:checkedAt,snapshotSha256:hash(data.canonical)};
const catalog=Buffer.from('{"cards":[]}');
const status={...device,source:'worker-get',workflowRunId:'9',workflowRunAttempt:'1',catalogSha256:hash(catalog),conflictCount:0};
const verify=(server,receipt=device,published=catalog)=>verifyPublished(server,published,9,1,now,receipt,now);
verify(status);
assert.throws(()=>validateDeviceReceipt({...device,pending:true},now),/pending writes/);
assert.throws(()=>validateDeviceReceipt(device,now+660000),/current/);
assert.throws(()=>verify({...status,workflowRunId:'8'}),/verified/);
assert.throws(()=>verify({...status,storageKeyCount:6}),/verified/);
assert.throws(()=>verify({...status,snapshotSha256:'a'.repeat(64)}),/snapshots differ/);
assert.throws(()=>verify(status,device,Buffer.from('{}')),/verified/);
assert.throws(()=>verify({...status,conflictCount:1}),/conflicts/);
verify({...status,conflictCount:1},null);
const uploadEvidence={version:1,scope:'worker-stored-snapshot',snapshotSha256:device.snapshotSha256,clientUploadAt:checkedAt};
verifySyncedOnly({...status,uploadEvidence});
assert.throws(()=>verifySyncedOnly(status),/No matching upload evidence/);
assert.throws(()=>verifySyncedOnly({...status,uploadEvidence:{...uploadEvidence,snapshotSha256:'a'.repeat(64)}}),/No matching upload evidence/);
assert.throws(()=>verifySyncedOnly({...status,uploadEvidence:{...uploadEvidence,clientUploadAt:new Date(now+1000).toISOString()}}),/No matching upload evidence/);
assert.throws(()=>verifySyncedOnly({...status,uploadEvidence,conflictCount:1}),/conflicts/);
console.log('Passed seven-entry integrity, edit history, stale receipt, pending writes, mismatched catalog, and conflict gate.');
